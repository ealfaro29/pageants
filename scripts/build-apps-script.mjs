// Bundles the scoresheet layout builder and the web app entry point into a single
// Code.gs to paste into the Google Apps Script project. Run after changing either file:
//   node scripts/build-apps-script.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const layoutPath = path.join(root, 'src/pages/scoring/scoresheet/googleSheetsLayout.js');
const webappPath = path.join(root, 'scripts/google-apps-script/webapp.js');
const outPath = path.join(root, 'scripts/google-apps-script/Code.gs');

const header = `/**
 * Pageants App – Google Sheets scoresheet generator (Apps Script web app).
 * GENERATED by scripts/build-apps-script.mjs — edit the source files, not this one.
 *
 * Setup (once, signed in with the Google account that should own the sheets):
 *  1. Open https://script.new and paste this whole file into Code.gs.
 *  2. Project Settings → tick "Show appsscript.json", then paste
 *     scripts/google-apps-script/appsscript.json into it (enables the Sheets service).
 *  3. Deploy → New deployment → type "Web app" → Execute as: Me →
 *     Who has access: Anyone → Deploy, and authorize the permissions.
 *  4. Copy the web app URL into GOOGLE_SHEETS_WEBAPP_URL in
 *     src/pages/scoring/scoresheet/googleSheetsExport.js.
 * After pasting a newer version: Deploy → Manage deployments → edit → Version: New.
 */
`;

const layout = (await fs.readFile(layoutPath, 'utf8'))
  .replace(/^export (?=(const|function|class|let) )/gm, '');
const webapp = await fs.readFile(webappPath, 'utf8');

await fs.writeFile(outPath, `${header}\n${layout}\n${webapp}`);
console.log(`Wrote ${path.relative(root, outPath)}`);
